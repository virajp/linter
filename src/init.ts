import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { resolve } from "node:path";

const ESLINT_CONFIG_MJS = `// Auto-generated by @askviraj/linter-cli
// Run \`npx @askviraj/linter-cli --init\` to regenerate.
export { default } from "@askviraj/linter-cli/auto";
`;

const LINTER_YAML = `# @askviraj/linter-cli configuration
#
# Add custom ignores, rule overrides, and additional config blocks below.

# ignores:
#   - "**/generated/**"
#   - "**/*.d.ts"
#
# overrides:
#   typescript:
#     rules:
#       "@typescript-eslint/no-explicit-any": "error"
#
# configs:
#   - name: "custom"
#     files: ["**/*.ts"]
#     rules: {}
`;

const VSCODE_SETTINGS: Record<string, unknown> = {
  "eslint.useFlatConfig": true,
};

/**
 * Strip JSONC comments (line and block comments) while preserving comments
 * inside strings. This is a minimal, safe implementation for VS Code settings files.
 */
function stripJsonComments(content: string): string {
  let result = "";
  let i = 0;

  while (i < content.length) {
    const ch = content[i];
    const next = content[i + 1];

    if (ch === "\"") {
      // String literal: copy verbatim until closing quote (handling escapes)
      result += ch;
      i++;
      while (i < content.length) {
        const sch = content[i];
        result += sch;
        if (sch === "\\") {
          i++;
          if (i < content.length) {
            result += content[i];
          }
        }
        else if (sch === "\"") {
          break;
        }
        i++;
      }
      i++;
    }
    else if (ch === "/" && next === "/") {
      // Line comment: skip to end of line
      while (i < content.length && content[i] !== "\n") {
        i++;
      }
    }
    else if (ch === "/" && next === "*") {
      // Block comment: skip to */
      i += 2;
      while (i < content.length) {
        if (content[i] === "*" && content[i + 1] === "/") {
          i += 2;
          break;
        }
        i++;
      }
    }
    else {
      result += ch;
      i++;
    }
  }

  return result;
}

/**
 * Strip trailing commas from JSON content while preserving commas inside strings.
 * VS Code settings files allow trailing commas, but JSON.parse does not.
 */
function stripTrailingCommas(content: string): string {
  let result = "";
  let i = 0;

  while (i < content.length) {
    const ch = content[i];

    if (ch === "\"") {
      // String literal: copy verbatim until closing quote (handling escapes)
      result += ch;
      i++;
      while (i < content.length) {
        const sch = content[i];
        result += sch;
        if (sch === "\\") {
          i++;
          if (i < content.length) {
            result += content[i];
          }
        }
        else if (sch === "\"") {
          break;
        }
        i++;
      }
      i++;
    }
    else if (ch === ",") {
      // Look ahead for ] or } (with optional whitespace)
      let j = i + 1;
      while (j < content.length) {
        const cj = content[j];
        if (cj === undefined || !/[\s]/.test(cj)) {
          break;
        }
        j++;
      }
      const cj = content[j];
      if (cj !== undefined && (cj === "]" || cj === "}")) {
        // Skip the trailing comma
        i++;
      }
      else {
        result += ch;
        i++;
      }
    }
    else {
      result += ch;
      i++;
    }
  }

  return result;
}

interface FileAction {
  path: string;
  action: "created" | "updated" | "skipped" | "overwritten" | "failed";
}

function mergeVsCodeSettings(existingPath: string): Record<string, unknown> {
  const raw = readFileSync(existingPath, "utf-8");
  const cleaned = stripTrailingCommas(stripJsonComments(raw));
  return JSON.parse(cleaned) as Record<string, unknown>;
}

export interface InitOptions {
  force?: boolean;
  cwd?: string;
}

export function runInit(options: InitOptions = {}): void {
  const cwd = options.cwd || process.cwd();
  const actions: FileAction[] = [];
  let settingsError: string | undefined;

  // 1. eslint.config.mjs
  const eslintConfigPath = resolve(cwd, "eslint.config.mjs");
  const eslintExisted = existsSync(eslintConfigPath);
  if (eslintExisted && !options.force) {
    actions.push({ path: eslintConfigPath, action: "skipped" });
  }
  else {
    try {
      writeFileSync(eslintConfigPath, ESLINT_CONFIG_MJS);
      actions.push({
        path: eslintConfigPath,
        action: eslintExisted ? "overwritten" : "created",
      });
    }
    catch (e) {
      console.error(
        `Failed to write ${eslintConfigPath}:`,
        e instanceof Error ? e.message : e,
      );
      process.exit(1);
    }
  }

  // 2. .config/linter.yaml
  const configDir = resolve(cwd, ".config");
  if (!existsSync(configDir)) {
    mkdirSync(configDir, { recursive: true });
  }
  const linterYamlPath = resolve(configDir, "linter.yaml");
  const linterExisted = existsSync(linterYamlPath);
  if (linterExisted && !options.force) {
    actions.push({ path: linterYamlPath, action: "skipped" });
  }
  else {
    try {
      writeFileSync(linterYamlPath, LINTER_YAML);
      actions.push({
        path: linterYamlPath,
        action: linterExisted ? "overwritten" : "created",
      });
    }
    catch (e) {
      console.error(
        `Failed to write ${linterYamlPath}:`,
        e instanceof Error ? e.message : e,
      );
      process.exit(1);
    }
  }

  // 3. .vscode/settings.json
  const vscodeDir = resolve(cwd, ".vscode");
  if (!existsSync(vscodeDir)) {
    mkdirSync(vscodeDir, { recursive: true });
  }
  const settingsPath = resolve(vscodeDir, "settings.json");
  if (existsSync(settingsPath)) {
    try {
      const existing = mergeVsCodeSettings(settingsPath);
      const merged = { ...existing, ...VSCODE_SETTINGS };
      writeFileSync(settingsPath, JSON.stringify(merged, null, 2) + "\n");
      actions.push({ path: settingsPath, action: "updated" });
    }
    catch (e) {
      settingsError = e instanceof Error ? e.message : String(e);
      actions.push({ path: settingsPath, action: "failed" });
    }
  }
  else {
    try {
      writeFileSync(
        settingsPath,
        JSON.stringify(VSCODE_SETTINGS, null, 2) + "\n",
      );
      actions.push({ path: settingsPath, action: "created" });
    }
    catch (e) {
      console.error(
        `Failed to write ${settingsPath}:`,
        e instanceof Error ? e.message : e,
      );
      process.exit(1);
    }
  }

  console.log("Initialized @askviraj/linter-cli:");
  for (const { path, action } of actions) {
    console.log(`  [${action}] ${path}`);
  }

  const skipped = actions.filter(a => a.action === "skipped");
  if (skipped.length > 0) {
    console.log("");
    console.log(
      "Some files were skipped because they already exist. Use --force to overwrite.",
    );
  }

  if (settingsError) {
    console.error(
      `\nFailed to update ${settingsPath}: ${settingsError}`,
    );
    console.error(
      "The file contains invalid JSONC. Fix the file and try again.",
    );
    process.exit(1);
  }

  console.log("");
  console.log(
    "Note: If you have VS Code open, restart the ESLint server (",
    "Cmd+Shift+P → 'ESLint: Restart ESLint Server'",
    ") or restart VS Code for changes to take effect.",
  );
}
